export const PROTOCOLS_BY_SLUG = new Map(PROTOCOLS.map((p) => [p.slug, p]));

/** Ranks protocols by keyword matches in the presenting complaint (best first). */
export function suggestProtocols(complaint: string, limit = 3): Protocol[] {
  const text = ` ${complaint.toLowerCase()} `;
  return PROTOCOLS.map((p) => ({ p, score: p.keywords.reduce((s, k) => s + (text.includes(k.toLowerCase()) ? k.split(' ').length + 1 : 0), 0) }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p);
}
